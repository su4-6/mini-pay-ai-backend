-- ---------------------------------------------------------------- 校验
-- 每个订单的明细合计必须等于 item_amount_cent；下面这条查询应返回 0 行。
SELECT o.order_no,
       o.item_amount_cent,
       COALESCE(SUM(i.line_amount_cent), 0) AS items_sum,
       o.item_amount_cent - COALESCE(SUM(i.line_amount_cent), 0) AS diff
  FROM minipay_commerce.food_order o
  LEFT JOIN minipay_commerce.food_order_item i ON i.order_id = o.order_id
 GROUP BY o.order_no, o.item_amount_cent
HAVING diff <> 0;
